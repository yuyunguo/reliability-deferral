"""Conformal prediction baseline for selective prediction comparison.

Compares three deferral strategies at matched coverage levels:
  1. Confidence gate (max predicted probability)
  2. Reliability gate (R composite)
  3. Conformal variance gate (ensemble SD with split-conformal calibration)

The conformal approach uses ensemble prediction variance as a nonconformity
score, calibrated on the validation set to provide finite-sample marginal
coverage guarantees. This serves as a distribution-free alternative to our
learned reliability composite.

Usage:
    python -m deferral_frontier.experiments.run_conformal_baseline sepsis
    python -m deferral_frontier.experiments.run_conformal_baseline mortality
    python -m deferral_frontier.experiments.run_conformal_baseline vasopressor

Requires: artifacts/{task}_test_artifacts.parquet and
          artifacts/{task}_val_artifacts.parquet (generated by run_deferral.py)
"""
import argparse
import logging
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.metrics import brier_score_loss, roc_auc_score

ARTIFACTS_DIR = Path("artifacts")
RESULTS_DIR = Path("deferral_frontier/results")
COVERAGE_TARGETS = np.array([0.50, 0.55, 0.60, 0.65, 0.70, 0.75, 0.80, 0.85, 0.90, 0.95, 1.00])

logger = logging.getLogger(__name__)


def conformal_quantile(
    nonconformity_val: np.ndarray,
    alpha: float,
) -> float:
    """Split-conformal quantile for 1-alpha coverage.

    q = quantile(alpha_values, ceil((1-alpha)(n+1)/n))
    Guarantees P(y in C(x)) >= 1-alpha for exchangeable data.
    """
    n = len(nonconformity_val)
    q_level = min(np.ceil((1 - alpha) * (n + 1)) / n, 1.0)
    return float(np.quantile(nonconformity_val, q_level))


def run_conformal_baseline(task: str) -> None:
    logger.info("=" * 60)
    logger.info("Conformal baseline comparison: %s", task)
    logger.info("=" * 60)

    RESULTS_DIR.mkdir(parents=True, exist_ok=True)

    test_path = ARTIFACTS_DIR / f"{task}_test_artifacts.parquet"
    val_path = ARTIFACTS_DIR / f"{task}_val_artifacts.parquet"
    if not test_path.exists():
        logger.error("Run run_deferral.py first to generate artifacts.")
        return

    test = pd.read_parquet(test_path)
    val = pd.read_parquet(val_path)

    y_test = test["y_true"].values
    cal_test = test["cal_proba"].values
    r_test = test["r_score"].values
    sd_test = test["ensemble_sd"].values
    sd_val = val["ensemble_sd"].values

    nonconformity_val = sd_val
    nonconformity_test = sd_test

    rows = []
    for coverage in COVERAGE_TARGETS:
        alpha = 1.0 - coverage
        n_test = len(y_test)
        n_predict = int(np.round(n_test * coverage))

        policies = {
            "confidence": -cal_test,
            "reliability": -r_test,
            "conformal_variance": nonconformity_test,
        }

        for policy_name, score in policies.items():
            idx = np.argsort(score)[:n_predict]
            y_sel = y_test[idx]
            p_sel = cal_test[idx]

            brier = float(brier_score_loss(y_sel, p_sel))
            try:
                auroc = float(roc_auc_score(y_sel, p_sel))
            except ValueError:
                auroc = np.nan

            rows.append({
                "task": task,
                "policy": policy_name,
                "coverage": coverage,
                "brier": brier,
                "auroc": auroc,
                "n_predicted": n_predict,
            })

        if coverage < 1.0:
            q = conformal_quantile(nonconformity_val, alpha)
            conformal_mask = nonconformity_test <= q
            empirical_coverage = float(conformal_mask.sum()) / n_test
            rows.append({
                "task": task,
                "policy": "conformal_calibrated",
                "coverage": empirical_coverage,
                "brier": float(brier_score_loss(y_test[conformal_mask],
                                                 cal_test[conformal_mask])),
                "auroc": _safe_auroc(y_test[conformal_mask], cal_test[conformal_mask]),
                "n_predicted": int(conformal_mask.sum()),
                "conformal_quantile": q,
                "target_coverage": coverage,
            })

    results_df = pd.DataFrame(rows)
    out_path = RESULTS_DIR / f"{task}_conformal_baseline.csv"
    results_df.to_csv(out_path, index=False)
    logger.info("Saved conformal baseline to %s", out_path)

    print(f"\n{'='*70}")
    print(f"  CONFORMAL BASELINE COMPARISON — {task.upper()}")
    print(f"{'='*70}")
    print(f"  {'Policy':25s} | {'Cov':>5s} | {'Brier':>7s} | {'AUROC':>7s}")
    print(f"  {'-'*25}-+-{'-'*5}-+-{'-'*7}-+-{'-'*7}")
    for _, r in results_df.iterrows():
        if r["coverage"] in (0.80, 0.95, 1.0):
            print(f"  {r['policy']:25s} | {r['coverage']:5.2f} | {r['brier']:7.4f} | {r['auroc']:7.4f}")
    print(f"{'='*70}\n")


def _safe_auroc(y, p):
    try:
        return float(roc_auc_score(y, p))
    except ValueError:
        return float("nan")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("task", type=str, nargs="?", default="sepsis")
    args = parser.parse_args()
    logging.basicConfig(level=logging.INFO, format="%(asctime)s [%(levelname)s] %(message)s")
    run_conformal_baseline(args.task)
